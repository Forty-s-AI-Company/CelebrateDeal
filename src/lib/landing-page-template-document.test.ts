import { describe, expect, it } from "vitest";
import { createFunnelFlow } from "@/lib/funnel-flow";
import { FUNNEL_CAPABILITIES, parsePageDocument, type FunnelNode, type FunnelNodeAction, type PageDocument } from "@/lib/funnel-page-document";
import { instantiateFunnelTemplate } from "@/lib/funnel-template-gallery";
import {
  LANDING_PAGE_TEMPLATE_MAX_CONTENT_BYTES,
  LANDING_PAGE_TEMPLATE_NAME_MAX_LENGTH,
  normalizeTemplateName,
  prepareStoredTemplateDocument,
  readStoredTemplateDocument,
  rekeyTemplateDocument,
  STORED_TEMPLATE_PAGE_ID,
  stripTemplateBindings,
  TEMPLATE_RESOURCE_PROP_KEYS,
  templateContentBytes,
} from "./landing-page-template-document";

const leaf = (id: string, type: FunnelNode["type"], props: Record<string, unknown> = {}, actions: FunnelNodeAction[] = [], extra: Partial<FunnelNode> = {}): FunnelNode => ({
  schemaVersion: 1, id, type, props, style: {}, overrides: {}, visible: true, actions, attributes: {}, ...extra,
});
const container = (id: string, type: FunnelNode["type"], children: FunnelNode[]): FunnelNode => ({ ...leaf(id, type), children });

/** Every vendor-bound value carries this marker, so a leak shows up in the serialized document. */
const MARK = "vendorBoundSecret";
const resourceProps = Object.fromEntries(TEMPLATE_RESOURCE_PROP_KEYS.map((key) => [key, `${MARK}_${key}`]));

function boundDocument(): PageDocument {
  const flow = createFunnelFlow({ id: "source_flow", name: "來源網站", goal: "sell", domain: "source-site" })!;
  const document = parsePageDocument({
    schemaVersion: 1,
    // The page id is regenerated by rekeying (see prepareStoredTemplateDocument), not by stripping.
    id: "source_page_1",
    name: "來源頁",
    revision: 42,
    settings: {
      tracking: { status: "available", reason: `${MARK}_tracking` },
      affiliate: { status: "available", reason: `${MARK}_affiliate` },
      seo: { title: "保留的 SEO 標題", hideFromSearch: false },
    },
    commerce: { schemaVersion: 1, productId: `${MARK}_product`, orderBumpProductId: `${MARK}_bump`, formMode: "two_step", agreement: { label: "同意條款" } },
    root: [container("section_main", "section", [container("row_main", "row", [container("col_main", "columns_2", [
      leaf("headline_main", "headline", { text: "保留的標題", level: "h1" }, [], { attributes: { id: "hero" } }),
      leaf("calendar_main", "calendar", { eventId: `${MARK}_event` }, [], { overrides: { mobile: { props: { calendarId: `${MARK}_calendar`, bookingEventId: `${MARK}_booking` }, visible: true }, desktop: { props: { title: "保留的覆寫" } } } }),
      leaf("text_props", "text", { text: "保留的內文", ...resourceProps }),
      leaf("raw_main", "raw_html", { html: "<div class=\"keep\">原樣保存的 HTML</div>" }),
      leaf("image_main", "image", { src: "/placeholder.svg", alt: "保留的圖片" }),
      leaf("cta_registration", "button", { label: "報名" }, [{ type: "registration", formId: `${MARK}_form`, useBoundLive: true }]),
      leaf("cta_next", "button", { label: "下一步" }, [{ type: "next_step", stepId: `${MARK}_step` }]),
      leaf("cta_submit", "button", { label: "送出" }, [{ type: "submit_form", formId: `${MARK}_submit_form` }]),
      leaf("cta_popup", "button", { label: "開啟彈窗" }, [{ type: "show_popup", popupId: "popup_offer" }]),
      leaf("cta_link", "button", { label: "外部連結" }, [{ type: "open_url", href: "https://example.test/keep", newTab: true }]),
      container("form_main", "form", [leaf("field_email", "form_input", { id: "email", label: "Email", inputType: "email" })]),
    ])])])],
    popups: [{ schemaVersion: 1, id: "popup_offer", name: "優惠彈窗", pageId: `${MARK}_popup_page`, root: [container("popup_section", "section", [container("popup_row", "row", [
      leaf("popup_cta", "button", { label: "預約" }, [{ type: "registration", formId: `${MARK}_popup_form`, useBoundLive: false }]),
      leaf("popup_calendar", "calendar", { bookingEventId: `${MARK}_popup_event` }),
    ])])] }],
  });
  if (!document) throw new Error("fixture must be a valid PageDocument");
  return { ...document, flow };
}

function flatten(nodes: FunnelNode[]): FunnelNode[] {
  return nodes.flatMap((node) => [node, ...flatten(node.children ?? [])]);
}
const allNodes = (document: PageDocument) => [...flatten(document.root), ...document.popups.flatMap((popup) => flatten(popup.root))];
const byOriginalOrder = (document: PageDocument, index: number) => allNodes(document)[index]!;

describe("stripTemplateBindings", () => {
  it("removes every vendor-resource and page binding while keeping the design", () => {
    const source = boundDocument();
    const stripped = stripTemplateBindings(source);
    const serialized = JSON.stringify(stripped);

    expect(serialized).not.toContain(MARK);
    expect(stripped.commerce).toBeUndefined();
    expect(stripped.flow).toBeUndefined();
    expect(stripped.revision).toBe(0);
    expect(stripped.settings.tracking).toEqual(FUNNEL_CAPABILITIES.tracking);
    expect(stripped.settings.affiliate).toEqual(FUNNEL_CAPABILITIES.affiliate);
    expect(stripped.popups[0]).not.toHaveProperty("pageId");
    // Design, text, links, HTML ids, field keys and raw_html stay exactly as they were.
    expect(stripped.settings.seo.title).toBe("保留的 SEO 標題");
    expect(serialized).toContain("保留的標題");
    expect(serialized).toContain("https://example.test/keep");
    const nodes = new Map(allNodes(stripped).map((node) => [node.id, node]));
    expect(nodes.get("headline_main")!.attributes).toEqual({ id: "hero" });
    expect(nodes.get("raw_main")!.props).toEqual({ html: "<div class=\"keep\">原樣保存的 HTML</div>" });
    expect(nodes.get("field_email")!.props).toEqual({ id: "email", label: "Email", inputType: "email" });
    expect(nodes.get("image_main")!.props).toEqual({ src: "/placeholder.svg", alt: "保留的圖片" });
    expect(nodes.get("calendar_main")!.overrides.desktop).toEqual({ props: { title: "保留的覆寫" } });
    // The source document is not mutated.
    expect(JSON.stringify(source)).toContain(`${MARK}_product`);
  });

  it.each(TEMPLATE_RESOURCE_PROP_KEYS)("drops the resource prop %s from props and viewport overrides", (key) => {
    const document = parsePageDocument({
      schemaVersion: 1, id: "page", root: [container("s", "section", [container("r", "row", [
        leaf("t", "text", { text: "內容", [key]: "resource-1" }, [], { overrides: { mobile: { props: { [key]: "resource-2", text: "手機版" } }, desktop: { props: { [key]: "resource-3" } } } }),
      ])])],
    })!;
    const node = flatten(stripTemplateBindings(document).root).find((item) => item.id === "t")!;
    expect(node.props).toEqual({ text: "內容" });
    expect(node.overrides.mobile?.props).toEqual({ text: "手機版" });
    expect(node.overrides.desktop?.props).toEqual({});
  });

  it("turns form, live and step targets into unconfigured actions", () => {
    const actions = (id: string) => allNodes(stripTemplateBindings(boundDocument())).find((node) => node.id === id)!.actions;
    expect(actions("cta_registration")).toEqual([{ type: "none" }]);
    expect(actions("cta_next")).toEqual([{ type: "none" }]);
    expect(actions("cta_submit")).toEqual([{ type: "submit_form" }]);
    expect(actions("cta_popup")).toEqual([{ type: "show_popup", popupId: "popup_offer" }]);
    expect(actions("cta_link")).toEqual([{ type: "open_url", href: "https://example.test/keep", newTab: true }]);
    expect(actions("popup_cta")).toEqual([{ type: "none" }]);
  });

  it("keeps a platform template valid after stripping", () => {
    const stripped = stripTemplateBindings(instantiateFunnelTemplate("sell-product-checkout", "checkout_page"));
    expect(parsePageDocument(stripped)).not.toBeNull();
  });
});

describe("rekeyTemplateDocument", () => {
  it("regenerates node, popup and page ids and keeps show_popup pointing at its popup", () => {
    const source = stripTemplateBindings(boundDocument());
    const rekeyed = rekeyTemplateDocument(source, "tx", "target_page");
    expect(rekeyed.id).toBe("target_page");
    const sourceIds = allNodes(source).map((node) => node.id);
    const ids = allNodes(rekeyed).map((node) => node.id);
    expect(ids).toHaveLength(sourceIds.length);
    expect(new Set(ids).size).toBe(ids.length);
    expect(ids.every((id) => id.startsWith("tx_n"))).toBe(true);
    expect(ids.some((id) => sourceIds.includes(id))).toBe(false);
    expect(rekeyed.popups.map((popup) => popup.id)).toEqual(["tx_p1"]);
    const popupButton = allNodes(rekeyed).find((node) => node.actions.some((action) => action.type === "show_popup"))!;
    expect(popupButton.actions).toEqual([{ type: "show_popup", popupId: "tx_p1" }]);
    // Same structure and content: only ids changed.
    expect(byOriginalOrder(rekeyed, 3)).toMatchObject({ type: byOriginalOrder(source, 3).type, props: byOriginalOrder(source, 3).props });
    expect(parsePageDocument(rekeyed)).not.toBeNull();
    expect(rekeyTemplateDocument(source, "tx", "target_page")).toEqual(rekeyed);
  });

  it("drops a show_popup action whose popup is missing", () => {
    const document = parsePageDocument({ schemaVersion: 1, id: "page", root: [container("s", "section", [container("r", "row", [leaf("b", "button", { label: "開啟" })])])] })!;
    const withDangling = structuredClone(document);
    flatten(withDangling.root).find((node) => node.id === "b")!.actions = [{ type: "show_popup", popupId: "gone" }];
    const node = flatten(rekeyTemplateDocument(withDangling, "ty", "p").root).find((item) => item.type === "button")!;
    expect(node.actions).toEqual([{ type: "none" }]);
  });
});

describe("stored template documents", () => {
  it("prepares a stripped, stable, named document", () => {
    const prepared = prepareStoredTemplateDocument(boundDocument(), "我的銷售頁");
    expect(prepared).not.toBeNull();
    expect(prepared!.id).toBe(STORED_TEMPLATE_PAGE_ID);
    expect(JSON.stringify(prepared)).not.toContain("source_page_1");
    expect(JSON.stringify(prepared)).not.toContain("section_main");
    expect(prepared!.name).toBe("我的銷售頁");
    expect(JSON.stringify(prepared)).not.toContain(MARK);
    expect(prepareStoredTemplateDocument(boundDocument(), "我的銷售頁")).toEqual(prepared);
  });

  it("refuses content over the size limit", () => {
    const long = "長".repeat(10_000);
    const document = parsePageDocument({ schemaVersion: 1, id: "page", root: [container("s", "section", [container("r", "row", Array.from({ length: 6 }, (_, index) => leaf(`t${index}`, "text", { text: long })))])] })!;
    expect(templateContentBytes(document)).toBeGreaterThan(LANDING_PAGE_TEMPLATE_MAX_CONTENT_BYTES);
    expect(prepareStoredTemplateDocument(document, "太大")).toBeNull();
  });

  it("strips again when reading, and rejects non-documents", () => {
    const read = readStoredTemplateDocument(boundDocument());
    expect(read).not.toBeNull();
    expect(JSON.stringify(read)).not.toContain(MARK);
    expect(readStoredTemplateDocument({ not: "a document" })).toBeNull();
    expect(readStoredTemplateDocument(null)).toBeNull();
  });
});

describe("normalizeTemplateName", () => {
  it("trims and collapses whitespace", () => {
    expect(normalizeTemplateName("  秋季  名單頁 ")).toBe("秋季 名單頁");
  });

  it("enforces 1–80 characters and rejects control characters", () => {
    expect(normalizeTemplateName("")).toBeNull();
    expect(normalizeTemplateName("   ")).toBeNull();
    expect(normalizeTemplateName(42)).toBeNull();
    expect(normalizeTemplateName("名".repeat(LANDING_PAGE_TEMPLATE_NAME_MAX_LENGTH))).toHaveLength(LANDING_PAGE_TEMPLATE_NAME_MAX_LENGTH);
    expect(normalizeTemplateName("名".repeat(LANDING_PAGE_TEMPLATE_NAME_MAX_LENGTH + 1))).toBeNull();
    expect(normalizeTemplateName("bad\u0000name")).toBeNull();
  });
});
