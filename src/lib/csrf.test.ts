import { createHmac, randomBytes } from "node:crypto";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

const requestContext = vi.hoisted(() => ({
  headerValues: {} as Record<string, string>,
  sessionValue: "session-a",
}));

vi.mock("next/headers", () => ({
  cookies: vi.fn(async () => ({
    get: () => ({ value: requestContext.sessionValue }),
  })),
  headers: vi.fn(async () => new Headers(requestContext.headerValues)),
}));

import { deriveCsrfMacKey, deriveSensitiveDataKey } from "@/lib/sensitive-data";
import {
  assertServerActionOrigin,
  assertServerActionSecurity,
  CSRF_FIELD_NAME,
  getCsrfToken,
  verifyCsrfToken,
} from "@/lib/csrf";

function setRequestContext(headerValues: Record<string, string> = {}, sessionValue = "session-a") {
  requestContext.headerValues = headerValues;
  requestContext.sessionValue = sessionValue;
}

// Independent re-statement of the CSRF construction: a purpose key derived
// from the root secret, then tagged messages under that key. The root secret
// itself never touches the (attacker-controlled) session cookie value.
function expectedCsrfKey() {
  return createHmac("sha256", process.env.CSRF_SECRET ?? "").update("CelebrateDeal:csrf-hmac:r2:db862e72a7b9a462").digest();
}

function expectedFingerprint(sessionValue: string) {
  return createHmac("sha256", expectedCsrfKey()).update(`csrf-fp:v1:${sessionValue}`).digest("base64url").slice(0, 32);
}

function signedCsrfValue(issuedAt: number, nonce = "nonce-a", fingerprint = "fingerprint-a") {
  const body = `${issuedAt}.${nonce}.${fingerprint}`;
  const signature = createHmac("sha256", expectedCsrfKey()).update(`csrf-token:v1:${body}`).digest("base64url");
  return `${body}.${signature}`;
}

// The pre-fix construction: HMAC(root secret, cookie) and HMAC(root secret, body).
function legacyCsrfValue(issuedAt: number, sessionValue: string, nonce = "nonce-legacy") {
  const root = process.env.CSRF_SECRET ?? "";
  const fingerprint = createHmac("sha256", root).update(sessionValue).digest("base64url").slice(0, 32);
  const body = `${issuedAt}.${nonce}.${fingerprint}`;
  return `${body}.${createHmac("sha256", root).update(body).digest("base64url")}`;
}

beforeEach(() => {
  vi.stubEnv("CSRF_SECRET", randomBytes(32).toString("base64url"));
  vi.stubEnv("NEXT_PUBLIC_APP_URL", "https://configured.example.test");
  setRequestContext({ host: "request.example.test" });
});

afterEach(() => {
  vi.unstubAllEnvs();
  vi.useRealTimers();
});

describe("assertServerActionOrigin", () => {
  it("rejects a cross-origin Origin", async () => {
    setRequestContext({ host: "request.example.test", origin: "https://attacker.example.test" });

    await expect(assertServerActionOrigin()).rejects.toThrow("Invalid request origin.");
  });

  it("rejects a cross-origin Referer", async () => {
    setRequestContext({ host: "request.example.test", referer: "https://attacker.example.test/form" });

    await expect(assertServerActionOrigin()).rejects.toThrow("Invalid request origin.");
  });

  it("accepts an Origin matching the configured app URL", async () => {
    setRequestContext({ host: "request.example.test", origin: "https://configured.example.test" });

    await expect(assertServerActionOrigin()).resolves.toBeUndefined();
  });

  it("accepts a Referer matching Host", async () => {
    vi.stubEnv("NEXT_PUBLIC_APP_URL", "");
    setRequestContext({ host: "request.example.test", referer: "https://request.example.test/form" });

    await expect(assertServerActionOrigin()).resolves.toBeUndefined();
  });

  it("does not let X-Forwarded-Host expand the origin allowlist", async () => {
    vi.stubEnv("NEXT_PUBLIC_APP_URL", "");
    setRequestContext({
      host: "request.example.test",
      "x-forwarded-host": "attacker.example.test",
      "x-forwarded-proto": "https",
      origin: "https://attacker.example.test",
    });

    await expect(assertServerActionOrigin()).rejects.toThrow("Invalid request origin.");
  });
});

describe("CSRF tokens", () => {
  it("fails closed in production instead of reusing JOB_SECRET", async () => {
    vi.stubEnv("NODE_ENV", "production");
    vi.stubEnv("CSRF_SECRET", "");
    vi.stubEnv("JOB_SECRET", "test-fixture-job-secret-that-must-not-sign-csrf");

    await expect(getCsrfToken()).rejects.toThrow("CSRF_SECRET must be configured in production.");
  });

  it("verifies a signed value generated by getCsrfToken", async () => {
    const csrfValue = await getCsrfToken();

    await expect(verifyCsrfToken(csrfValue)).resolves.toBe(true);
  });

  it("rejects missing and malformed values", async () => {
    await expect(verifyCsrfToken(null)).resolves.toBe(false);
    await expect(verifyCsrfToken("only.three.parts")).resolves.toBe(false);
    await expect(verifyCsrfToken(".nonce.fingerprint.signature")).resolves.toBe(false);
  });

  it("binds values to the current session fingerprint", async () => {
    const csrfValue = await getCsrfToken();
    setRequestContext({ host: "request.example.test" }, "session-b");

    await expect(verifyCsrfToken(csrfValue)).resolves.toBe(false);
  });

  it("rejects expired values and timestamps more than one minute in the future", async () => {
    vi.useFakeTimers();
    const now = new Date("2026-07-14T12:00:00.000Z");
    vi.setSystemTime(now);
    const currentValue = await getCsrfToken();
    const [, nonce, fingerprint] = currentValue.split(".");

    const ttlBoundaryValue = signedCsrfValue(now.getTime() - (2 * 60 * 60 * 1000), nonce, fingerprint);
    const futureBoundaryValue = signedCsrfValue(now.getTime() + 60_000, nonce, fingerprint);
    const expiredValue = signedCsrfValue(now.getTime() - (2 * 60 * 60 * 1000) - 1, nonce, fingerprint);
    const futureValue = signedCsrfValue(now.getTime() + 60_001, nonce, fingerprint);

    await expect(verifyCsrfToken(ttlBoundaryValue)).resolves.toBe(true);
    await expect(verifyCsrfToken(futureBoundaryValue)).resolves.toBe(true);
    await expect(verifyCsrfToken(expiredValue)).resolves.toBe(false);
    await expect(verifyCsrfToken(futureValue)).resolves.toBe(false);
  });

  it("rejects tampering with every signed part", async () => {
    const csrfValue = await getCsrfToken();
    const [issuedAt, nonce, fingerprint, signature] = csrfValue.split(".");
    const changedValues = [
      `${Number(issuedAt) + 1}.${nonce}.${fingerprint}.${signature}`,
      `${issuedAt}.other-nonce.${fingerprint}.${signature}`,
      `${issuedAt}.${nonce}.other-fingerprint.${signature}`,
      `${issuedAt}.${nonce}.${fingerprint}.${signature.slice(0, -1)}${signature.endsWith("x") ? "y" : "x"}`,
    ];

    for (const changedValue of changedValues) {
      await expect(verifyCsrfToken(changedValue)).resolves.toBe(false);
    }
  });
});

describe("CSRF key separation from the sensitive-data KDF", () => {
  const PURPOSES = [
    "mfa-encryption",
    "mfa-recovery-code-authentication",
    "commerce-order-buyer",
    "commerce-order-identity-fingerprint",
    "form-submission-email-verification",
    "form-submission-chat-session",
    "student-portal-access-token-v1",
    "merchant-registration-invite",
    "merchant-registration-invite-v2",
    "csrf-hmac-v1",
    // Purposes rotated after #485 (derived-key-purposes.ts).
    "csrf-hmac:r2:db862e72a7b9a462",
    "merchant-registration-invite:r2:9ecb5a622edbf327",
    "merchant-invite-email:r2:bcaa6cb59eb97af3",
  ];

  it.each(PURPOSES)("does not hand out the %s key prefix through a crafted session cookie", async (purpose) => {
    const cookieValue = `CelebrateDeal:${purpose}`;
    setRequestContext({ host: "request.example.test" }, cookieValue);
    const derivedKeyPrefix = deriveSensitiveDataKey(purpose).toString("base64url").slice(0, 32);
    const legacyFingerprint = createHmac("sha256", process.env.CSRF_SECRET ?? "")
      .update(cookieValue).digest("base64url").slice(0, 32);
    const [, , fingerprint] = (await getCsrfToken()).split(".");

    // Sanity: the pre-fix construction really did hand out the derived key prefix.
    expect(legacyFingerprint).toBe(derivedKeyPrefix);
    expect(fingerprint).toHaveLength(32);
    expect(fingerprint).not.toBe(legacyFingerprint);
    expect(fingerprint).toBe(expectedFingerprint(cookieValue));
  });

  it("derives its MAC key from the KDF under its own purpose and tags every message", async () => {
    const sessionValue = "CelebrateDeal:mfa-encryption";
    setRequestContext({ host: "request.example.test" }, sessionValue);

    expect(expectedCsrfKey().equals(deriveSensitiveDataKey("csrf-hmac:r2:db862e72a7b9a462"))).toBe(true);
    // The guessable pre-rotation purpose is no longer the CSRF key.
    expect(deriveCsrfMacKey(process.env.CSRF_SECRET ?? "").equals(deriveSensitiveDataKey("csrf-hmac-v1"))).toBe(false);
    expect(deriveCsrfMacKey(process.env.CSRF_SECRET ?? "").equals(expectedCsrfKey())).toBe(true);
    const csrfValue = await getCsrfToken();
    const [issuedAt, nonce, fingerprint] = csrfValue.split(".");
    expect(fingerprint).toBe(expectedFingerprint(sessionValue));
    expect(csrfValue).toBe(signedCsrfValue(Number(issuedAt), nonce, fingerprint));
  });

  it("keeps working with the non-production development fallback secret", async () => {
    vi.stubEnv("CSRF_SECRET", "");
    vi.stubEnv("JOB_SECRET", "");

    await expect(verifyCsrfToken(await getCsrfToken())).resolves.toBe(true);
  });

  it("rejects a token minted with the pre-fix construction without throwing", async () => {
    vi.useFakeTimers();
    vi.setSystemTime(new Date("2026-10-25T12:00:00.000Z"));
    const stale = legacyCsrfValue(Date.now() - 60_000, "session-a");
    const formData = new FormData();
    formData.set(CSRF_FIELD_NAME, stale);
    setRequestContext({ host: "request.example.test", origin: "https://configured.example.test" });

    await expect(verifyCsrfToken(stale)).resolves.toBe(false);
    await expect(assertServerActionSecurity(formData)).rejects.toThrow("Invalid CSRF token.");
  });
});

describe("assertServerActionSecurity", () => {
  it("accepts FormData carrying a valid value for the CSRF field", async () => {
    setRequestContext({ host: "request.example.test", origin: "https://configured.example.test" });
    const csrfValue = await getCsrfToken();
    const formData = new FormData();
    formData.set(CSRF_FIELD_NAME, csrfValue);

    await expect(assertServerActionSecurity(formData)).resolves.toBeUndefined();
  });

  it("rejects FormData missing the CSRF field", async () => {
    setRequestContext({ host: "request.example.test", origin: "https://configured.example.test" });

    await expect(assertServerActionSecurity(new FormData())).rejects.toThrow("Invalid CSRF token.");
  });

  it("rejects FormData with an invalid CSRF field value", async () => {
    setRequestContext({ host: "request.example.test", origin: "https://configured.example.test" });
    const formData = new FormData();
    formData.set(CSRF_FIELD_NAME, "invalid");

    await expect(assertServerActionSecurity(formData)).rejects.toThrow("Invalid CSRF token.");
  });
});
